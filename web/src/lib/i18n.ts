export const dictionaries = { ru, en };
export function translate(lang: Lang, key: string): string {
  return dictionaries[lang][key as Key] ?? en[key as Key] ?? key;
}
export function locale(lang: Lang) {
  return lang === 'ru' ? 'ru-RU' : 'en-GB';
}
export function number(value: number, lang: Lang, digits = 0) {
  return new Intl.NumberFormat(locale(lang), { maximumFractionDigits: digits }).format(value);
}
export function date(value: string | null | undefined, lang: Lang, time = false) {
  return value && Number.isFinite(Date.parse(value))
    ? new Intl.DateTimeFormat(locale(lang), {
        timeZone: 'Europe/Moscow',
        dateStyle: 'medium',
        ...(time ? { timeStyle: 'short' as const } : {}),
      }).format(new Date(value))
    : translate(lang, 'unknown');
}
export function moscowDay(value: string) {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Europe/Moscow',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date(value));
}
